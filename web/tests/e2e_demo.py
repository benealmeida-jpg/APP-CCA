        expect(pg.get_by_role('heading', name='Compradores')).to_be_visible()
        pg.click('text=Continuar')
        expect(pg.get_by_text('Digite o nome completo do titular.')).to_be_visible()
        pg.fill('#c-nome', 'Lucas Ferreira Lima')
        pg.fill('#c-cpf', '52998224725')
        assert pg.input_value('#c-cpf') == '529.982.247-25', pg.input_value('#c-cpf')
        pg.fill('#c-celular', '21987654321')
        pg.fill('#c-email', 'lucas@email.com')
        pg.get_by_role('button', name='Casado(a)').first.click()
        pg.click('text=Continuar')
        expect(pg.get_by_text('Responda se o cônjuge tem renda.')).to_be_visible()
        pg.locator('fieldset', has_text='cônjuge tem renda').get_by_role('button', name='Não').click()
        expect(pg.get_by_text('Entra como cônjuge')).to_be_visible()
        pg.fill('#cj-nome', 'Paula Lima'); pg.fill('#cj-cpf', '11144477735')
        pg.click('text=Adicionar comprador para compor renda')
        pg.fill('#p0-nome', 'Marcos Lima'); pg.fill('#p0-cpf', '52998224725')
        pg.locator('section', has_text='Comprador 3').get_by_role('button', name='Solteiro(a)').click()
        pg.click('text=Continuar')
        expect(pg.get_by_text('CPF do comprador 3 repetido.')).to_be_visible()
        pg.fill('#p0-cpf', '39053344705')
        foto(pg, '03-etapa1')
        pg.click('text=Continuar')

        # Etapa 2
        expect(pg.get_by_role('heading', name='Operação')).to_be_visible()
        pg.get_by_role('button', name='Aquisição de Imóvel', exact=True).click()
        pg.get_by_role('button', name='MCMV').click()
        pg.get_by_role('button', name='Leilão').click()
        pg.get_by_role('button', name='Construtora / PJ').click()
        expect(pg.get_by_role('dialog')).to_be_visible()
        expect(pg.get_by_text('recurso da Caixa').first).to_be_visible()
        foto(pg, '04a-janela-pj')
        pg.get_by_role('dialog').get_by_role('button', name='Sim').click()
        expect(pg.get_by_role('dialog')).to_have_count(0)
        expect(pg.get_by_text('Alterar').first).to_be_visible()
        foto(pg, '04b-pj-respondido')
        pg.get_by_role('button', name='Pessoa física').click()
        pg.locator('fieldset', has_text='FGTS').get_by_role('button', name='Sim').click()
        foto(pg, '04-etapa2')
        pg.click('text=Continuar')

        # Etapa 3
        expect(pg.get_by_role('heading', name='Renda e dependentes')).to_be_visible()
        expect(pg.get_by_text('Renda de Marcos Lima')).to_be_visible()
        pg.get_by_role('button', name='Mista').first.click()
        expect(pg.locator('#c-renda-formal')).to_be_visible()
        pg.fill('#c-renda-formal', '300000'); pg.fill('#c-renda-informal', '150000')
        expect(pg.get_by_text('Renda bruta total: R$').first).to_be_visible()
        pg.get_by_role('button', name='Pró-labore').first.click()
        expect(pg.get_by_text('DEFIS dos últimos 2 anos').first).to_be_visible()
        pg.get_by_role('button', name='Formal', exact=True).first.click()
        pg.fill('#c-renda', '520000')
        assert 'R$' in pg.input_value('#c-renda') and '5.200,00' in pg.input_value('#c-renda'), pg.input_value('#c-renda')
        pg.click('text=Continuar')
        expect(pg.get_by_text('Responda se Lucas declara Imposto de Renda.')).to_be_visible()
        pg.get_by_role('button', name='Informal').first.click()
        pg.fill('#c-renda', '400000')
        pg.locator('fieldset', has_text='declara Imposto').first.get_by_role('button', name='Não').click()
        expect(pg.get_by_text('Renda considerada: R$').first).to_be_visible()
        foto(pg, '05b-corte-informal')
        pg.get_by_role('button', name='Formal', exact=True).first.click()
        pg.fill('#c-renda', '520000')
        pg.locator('fieldset', has_text='declara Imposto').first.get_by_role('button', name='Sim').click()
        expect(pg.get_by_text('IR entregue depois do prazo').first).to_be_visible()
        pg.locator('fieldset', has_text='retificação').get_by_role('button', name='Sim').click()
        sec = pg.locator('section', has_text='Renda de Marcos Lima')
        sec.get_by_role('button', name='Informal').click()
        pg.fill('#r1-renda', '200000')
        sec.locator('fieldset', has_text='Imposto').get_by_role('button', name='Não').click()
        expect(pg.get_by_text('Renda total dos compradores: R$ 7.200,00')).to_be_visible()
