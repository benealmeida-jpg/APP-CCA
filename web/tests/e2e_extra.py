"""Casos extras: operação sem vendedor pula a tela Vendedor; vendedor PF casado pede cônjuge e certidão de casamento."""
import os, re, sys, subprocess, time, tempfile
from playwright.sync_api import sync_playwright, expect

RAIZ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SAIDA = sys.argv[1] if len(sys.argv) > 1 else tempfile.mkdtemp()
srv = subprocess.Popen([sys.executable, '-m', 'http.server', '8766', '--bind', '127.0.0.1'], cwd=RAIZ, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(1)
URL = 'http://127.0.0.1:8766/index.html?demo'
erros = []
try:
    with sync_playwright() as p:
        b = p.chromium.launch(executable_path='/opt/pw-browsers/chromium-1194/chrome-linux/chrome')
        pg = b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True).new_page()
        pg.on('pageerror', lambda e: erros.append(str(e)))
        pg.goto(URL)
        pg.fill('#email', 'corretor@demo'); pg.fill('#senha', 'demo'); pg.click('button[type=submit]')
        pg.wait_for_timeout(900); pg.evaluate("location.hash = '#/clientes'"); expect(pg.get_by_role('heading', name='Meus clientes')).to_be_visible()

        # 1) Mariana: vendedor PF passa a ser casado
        mariana = pg.evaluate("JSON.parse(localStorage.getItem('appcca-demo-v8')).clientes.find(c => c.nome === 'Mariana Costa').id")
        pg.goto(f'{URL}#/cliente/{mariana}/cadastro/5')
        expect(pg.get_by_role('heading', name='Vendedor', exact=True)).to_be_visible()
        assert pg.input_value('#v-nome') == 'Antônio Ferreira'
        pg.locator('fieldset', has_text='Estado civil do vendedor').get_by_role('button', name='Casado(a)').click()
        expect(pg.get_by_text('Cônjuge também é vendedor:')).to_be_visible()
        pg.click('text=Continuar')
        expect(pg.get_by_text('Digite o nome completo do cônjuge do vendedor.')).to_be_visible()
        pg.fill('#v-conjuge_nome', 'Beatriz Ferreira'); pg.fill('#v-conjuge_cpf', '52998224725')
        pg.click('text=Continuar')
        expect(pg.get_by_text('Escolha o regime de bens do casamento do vendedor.')).to_be_visible()
        pg.locator('fieldset', has_text='Regime de bens').get_by_role('button', name='Separação total (convencional)').click()
        expect(pg.get_by_text('exige pacto antenupcial', exact=False)).to_be_visible()
        pg.screenshot(path=os.path.join(SAIDA, 'x1-vendedor-pf-casado.png'), full_page=True)
        pg.click('text=Continuar')
        expect(pg.get_by_role('heading', name='Documentos')).to_be_visible()
        pg.get_by_role('tab', name=re.compile('^Vendedor')).click()
        expect(pg.locator('.doc-nome', has_text='Certidão de casamento')).to_be_visible()
        expect(pg.locator('.doc-nome', has_text='Cônjuge do vendedor: identificação')).to_be_visible()
        expect(pg.locator('.doc-nome', has_text='Pacto antenupcial e registro do pacto')).to_be_visible()
        expect(pg.locator('.doc-nome', has_text='Certidão de nascimento')).to_have_count(0)
        pg.screenshot(path=os.path.join(SAIDA, 'x2-docs-vendedor-pf.png'), full_page=True)

        # 2) Construção em terreno próprio: sem tela Vendedor (6 etapas)
        pg.goto(f'{URL}#/cliente/{mariana}/cadastro/3')
        pg.get_by_role('button', name='Construção em Terreno Próprio').click()
        pg.locator('fieldset', has_text='3 anos ou mais').get_by_role('button', name='Não').click()
        pg.click('text=Continuar')
        expect(pg.get_by_role('heading', name='Imóvel', exact=True)).to_be_visible()
        expect(pg.get_by_text('Etapa 4 de 6', exact=False)).to_be_visible()
        expect(pg.get_by_role('button', name='Leilão')).to_have_count(0)
        pg.select_option('#imovel-uf', 'RJ'); pg.select_option('#imovel-municipio', 'Maricá')
        pg.get_by_role('button', name='Urbana').click()
        expect(pg.get_by_text('Teto MCMV Faixas 1 e 2 em Maricá: R$ 264.000,00')).to_be_visible()
        pg.fill('#valor-imovel', '20000000')
        if pg.locator('fieldset', has_text='primeira aquisição imobiliária').count():
            pg.locator('fieldset', has_text='primeira aquisição imobiliária').get_by_role('button', name='Não').click()
        if pg.locator('fieldset', has_text='trabalha, ou onde mora').count():
            pg.locator('fieldset', has_text='trabalha, ou onde mora').get_by_role('button', name='Sim').click()
            pg.locator('fieldset', has_text='já tem imóvel residencial').get_by_role('button', name='Não').click()
        pg.click('text=Continuar')
        expect(pg.get_by_role('heading', name='Documentos')).to_be_visible()
        expect(pg.get_by_text('Etapa 5 de 6', exact=False)).to_be_visible()
        expect(pg.get_by_role('tab', name=re.compile('^Vendedor'))).to_have_count(0)
        pg.get_by_role('link', name='Voltar').click()
        expect(pg.get_by_role('heading', name='Imóvel', exact=True)).to_be_visible()
        # 3) Convite: equipe convida corretor, ele abre o link, cria a senha e entra
        pg.goto(URL + '#/')
        pg.click('.usuario-botao'); pg.get_by_role('menuitem', name='Sair').click(); time.sleep(0.8)
        pg.set_viewport_size({'width': 1440, 'height': 1000})
        pg.fill('#email', 'equipe@demo'); pg.fill('#senha', 'demo'); pg.click('button[type=submit]')
        pg.click('.menu-botoes a:has-text("Imobiliárias")')
        pg.get_by_role('button', name='Cadastrar nova imobiliária').click()
        pg.fill('#im-nova-cnpj', '11222333000181'); expect(pg.get_by_text('Situação na Receita: ATIVA', exact=False)).to_be_visible(); pg.fill('#im-nova-nome', 'Imobiliária Nova Era')
        pg.get_by_role('button', name='Cadastrar imobiliária').click()
        expect(pg.get_by_text('Imobiliária cadastrada.')).to_be_visible()
        pg.click('.menu-botoes a:has-text("Corretores")')
        pg.get_by_role('button', name='Cadastrar novo corretor').click()
        pg.fill('#cv-nome', 'Carla Teixeira'); pg.fill('#cv-email', 'carla@novaera.com'); pg.fill('#cv-whats', '21988887777')
        pg.select_option('#cv-imob', label='Imobiliária Nova Era')
        pg.get_by_role('button', name='Cadastrar e gerar acesso').click()
        expect(pg.get_by_text('Cadastro criado.', exact=False)).to_be_visible()
        expect(pg.get_by_role('link', name='Enviar pelo WhatsApp')).to_have_attribute('href', re.compile(r'^https://wa\.me/5521988887777\?text='))
        link = re.search(r'(http\S+#/acesso\?token_hash=\S+)', pg.locator('.aviso-azul .balao').first.inner_text()).group(1)
        pg.screenshot(path=os.path.join(SAIDA, 'x3-convite.png'), full_page=True)
        # base de vendedores
        pg.click('.menu-botoes a:has-text("Vendedores")')
        pg.locator('tr', has_text='Construtora Exemplo Ltda').click()
        expect(pg.get_by_text('Processos com este vendedor (2)')).to_be_visible()
        pg.fill('#vd-conta_digito', '8')
        pg.get_by_role('button', name='Salvar dados').click()
        expect(pg.get_by_text('Dados do vendedor salvos.')).to_be_visible()
        pg.screenshot(path=os.path.join(SAIDA, 'x4-vendedores.png'), full_page=True)
        pg.click('.usuario-botao'); pg.click('.usuario-menu .sair-item'); time.sleep(0.8)
        expect(pg.locator('#email')).to_be_visible()  # espera terminar de sair antes de abrir o link
        # corretor abre o link
        pg.set_viewport_size({'width': 390, 'height': 844})
        pg.goto(link)
        expect(pg.get_by_role('heading', name='Bem-vindo ao Portal do Corretor')).to_be_visible()
        pg.fill('#nova-senha', 'senha123'); pg.fill('#nova-senha-2', 'senha124')
        pg.get_by_role('button', name='Salvar senha e entrar').click()
        expect(pg.get_by_text('As duas senhas não são iguais.')).to_be_visible()
        pg.fill('#nova-senha-2', 'senha123')
        pg.screenshot(path=os.path.join(SAIDA, 'x5-criar-senha.png'), full_page=True)
        pg.get_by_role('button', name='Salvar senha e entrar').click()
        pg.wait_for_timeout(900); pg.evaluate("location.hash = '#/clientes'"); expect(pg.get_by_role('heading', name='Meus clientes')).to_be_visible()
        expect(pg.get_by_text(re.compile(r', Carla\.'))).to_be_visible()
        # o mesmo link não funciona de novo
        pg.goto(link)
        expect(pg.get_by_text('Link inválido.')).to_be_visible()
        # 4) Documentação da imobiliária: vê clientes de todos os corretores e escolhe o responsável
        pg.goto(URL + '#/')
        if pg.locator('#email').count() == 0: pg.click('.usuario-botao'); pg.get_by_role('menuitem', name='Sair').click(); time.sleep(0.8)
        pg.fill('#email', 'doc@demo'); pg.fill('#senha', 'demo'); pg.click('button[type=submit]')
        pg.wait_for_timeout(900); pg.evaluate("location.hash = '#/clientes'"); expect(pg.get_by_role('heading', name='Meus clientes')).to_be_visible()
        expect(pg.locator('tbody td', has_text='João Alves').first).to_be_visible()
        expect(pg.locator('tbody td', has_text='Ana Ribeiro').first).to_be_visible()
        pg.get_by_role('link', name='Novo cliente').first.click()
        expect(pg.locator('#corretor-resp')).to_be_visible()
        pg.select_option('#corretor-resp', label='Ana Ribeiro')
        pg.screenshot(path=os.path.join(SAIDA, 'x6-gestor-escolhe-corretor.png'), full_page=True)
        pg.goto(URL + '#/')
        pg.click('.usuario-botao'); pg.get_by_role('menuitem', name='Sair').click(); time.sleep(0.8)
        # 5) ADM: canal de avisos e destino por imobiliária
        pg.set_viewport_size({'width': 1440, 'height': 1000})
        pg.fill('#email', 'equipe@demo'); pg.fill('#senha', 'demo'); pg.click('button[type=submit]')
        pg.click('.menu-botoes a:has-text("Imobiliárias")')
        linha = pg.locator('tr', has_text='Imobiliária Nova Era')
        linha.get_by_role('button', name='Os dois').click()
        expect(pg.get_by_text('Imobiliária Nova Era: avisos vão para os dois.')).to_be_visible()
        pg.click('.menu-botoes a:has-text("Configurações")')
        expect(pg.get_by_role('heading', name='Avisos aos corretores')).to_be_visible()
        pg.get_by_role('button', name='WhatsApp – API Meta (com custo)').click()
        expect(pg.get_by_label('ID do número de telefone (Phone Number ID)')).to_be_visible()
        pg.fill('#int-meta_phone_id', '123456789'); pg.locator('.campo', has=pg.locator('#int-meta_phone_id')).get_by_role('button', name='Salvar').click()
        expect(pg.get_by_text('guardado com segurança')).to_be_visible()
        pg.screenshot(path=os.path.join(SAIDA, 'x7-config-avisos.png'), full_page=True)
        pg.get_by_role('button', name='Notificação do app – Push (sem custo)').click()
        expect(pg.get_by_role('button', name='Enviar notificação de teste para mim')).to_be_visible()
        b.close()
    assert not erros, erros
    print('OK – casos extras')
finally:
    srv.terminate()
